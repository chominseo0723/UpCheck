'use strict';
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const read = name => fs.readFileSync(path.join(root, 'src', name), 'utf8').replace(/^\uFEFF/, '').replace(/\r\n/g, '\n');
const core = read('Core.js');
const code = read('Code.gs');
const html = read('Index.html');
const bundle = '// Generated by node scripts/build.cjs. Edit src/, then rebuild.\n' + core + '\n' + code + '\nconst EMAIL_SERVICE_HTML_ = ' + JSON.stringify(html).replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029') + ';\n';
new vm.Script(bundle, { filename: 'Deploy.gs' });
const manifest = JSON.stringify(JSON.parse(read('appsscript.json')), null, 2) + '\n';
const outputs = { 'Deploy.gs': bundle, 'appsscript.json': manifest };
if (process.argv.includes('--check')) {
  for (const [name, content] of Object.entries(outputs)) {
    if (fs.readFileSync(path.join(root, 'build', name), 'utf8') !== content) throw new Error('Stale build/' + name + ': run npm run build');
  }
  console.log('PASS: build matches src and bundle syntax is valid.');
} else {
  fs.mkdirSync(path.join(root, 'build'), { recursive: true });
  for (const [name, content] of Object.entries(outputs)) fs.writeFileSync(path.join(root, 'build', name), content);
  console.log('Built build/Deploy.gs and build/appsscript.json. No credentials are embedded.');
}
